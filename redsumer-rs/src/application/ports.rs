//! Contracts to produce and consume messages in a stream.
//!
//! Implement these traits to connect the producer and consumer services to a specific message broker (e.g. Redis Streams), or to an in-memory fake for testing purposes.

use crate::domain::message::{FieldValue, Message, MessageId};
use crate::domain::pending::PendingMessageInfo;
use crate::domain::result::RedsumerResult;
use crate::domain::stream::{ConsumerName, GroupName, StreamName};

/// Contract to produce messages in a stream.
pub trait MessageProducer {
    /// Produce a new message in a stream. The message ID is generated by the message broker.
    ///
    /// # Arguments:
    /// - **stream**: The stream where the message will be produced.
    /// - **fields**: The fields of the message as a list of name/value pairs.
    ///
    /// # Returns:
    /// A [`RedsumerResult`] with the ID of the produced message.
    fn produce(
        &mut self,
        stream: &StreamName,
        fields: &[(String, FieldValue)],
    ) -> RedsumerResult<MessageId>;
}

/// Contract to consume messages from a stream using consumers groups.
pub trait MessageConsumer {
    /// Verify that a stream exists.
    ///
    /// # Arguments:
    /// - **stream**: The stream to verify.
    ///
    /// # Returns:
    /// A [`RedsumerResult`] with `()` if the stream exists. Otherwise, an error is returned.
    fn ensure_stream_exists(&mut self, stream: &StreamName) -> RedsumerResult<()>;

    /// Create a consumers group in a stream if it does not exist yet.
    ///
    /// # Arguments:
    /// - **stream**: The stream where the group will be created.
    /// - **group**: The consumers group name.
    /// - **since_id**: The ID of the message to start consuming from.
    ///
    /// # Returns:
    /// A [`RedsumerResult`] with `true` if the group was created, or `false` if it already existed.
    fn ensure_consumer_group(
        &mut self,
        stream: &StreamName,
        group: &GroupName,
        since_id: &MessageId,
    ) -> RedsumerResult<bool>;

    /// Read new messages from a stream: messages that have never been delivered to any consumer in the group.
    ///
    /// # Arguments:
    /// - **stream**: The stream to read from.
    /// - **group**: The consumers group name.
    /// - **consumer**: The consumer name.
    /// - **count**: The maximum number of messages to read. If it is zero, no messages are read.
    /// - **block**: The time in milliseconds to block waiting for new messages.
    ///
    /// # Returns:
    /// A [`RedsumerResult`] with the list of new messages.
    fn read_new_messages(
        &mut self,
        stream: &StreamName,
        group: &GroupName,
        consumer: &ConsumerName,
        count: usize,
        block: usize,
    ) -> RedsumerResult<Vec<Message>>;

    /// Read messages that are pending in the consumer own pending list.
    ///
    /// # Arguments:
    /// - **stream**: The stream to read from.
    /// - **group**: The consumers group name.
    /// - **consumer**: The consumer name.
    /// - **latest_pending_message_id**: The cursor ID to start reading from.
    /// - **count**: The maximum number of messages to read. If it is zero, no messages are read.
    ///
    /// # Returns:
    /// A [`RedsumerResult`] with the list of pending messages and the next cursor ID.
    fn read_pending_messages(
        &mut self,
        stream: &StreamName,
        group: &GroupName,
        consumer: &ConsumerName,
        latest_pending_message_id: &MessageId,
        count: usize,
    ) -> RedsumerResult<(Vec<Message>, MessageId)>;

    /// Claim messages that are pending in other consumers pending lists, according to a minimum idle time.
    ///
    /// # Arguments:
    /// - **stream**: The stream to claim from.
    /// - **group**: The consumers group name.
    /// - **consumer**: The consumer name that will own the claimed messages.
    /// - **min_idle_time**: The minimum idle time in milliseconds to claim a message.
    /// - **next_id_to_claim**: The cursor ID to start claiming from.
    /// - **count**: The maximum number of messages to claim. If it is zero, no messages are claimed.
    ///
    /// # Returns:
    /// A [`RedsumerResult`] with the list of claimed messages and the next cursor ID.
    fn claim_pending_messages(
        &mut self,
        stream: &StreamName,
        group: &GroupName,
        consumer: &ConsumerName,
        min_idle_time: usize,
        next_id_to_claim: &MessageId,
        count: usize,
    ) -> RedsumerResult<(Vec<Message>, MessageId)>;

    /// Get pending information about a specific message in the consumer pending list.
    ///
    /// # Arguments:
    /// - **stream**: The stream where the message lives.
    /// - **group**: The consumers group name.
    /// - **consumer**: The consumer name.
    /// - **id**: The ID of the message to inspect.
    ///
    /// # Returns:
    /// A [`RedsumerResult`] with `Some(`[`PendingMessageInfo`]`)` if the message is still in the consumer pending list, or `None` otherwise.
    fn get_pending_info(
        &mut self,
        stream: &StreamName,
        group: &GroupName,
        consumer: &ConsumerName,
        id: &MessageId,
    ) -> RedsumerResult<Option<PendingMessageInfo>>;

    /// Acknowledge a message in a consumers group.
    ///
    /// # Arguments:
    /// - **stream**: The stream where the message lives.
    /// - **group**: The consumers group name.
    /// - **id**: The ID of the message to acknowledge.
    ///
    /// # Returns:
    /// A [`RedsumerResult`] with `true` if the message was acknowledged, or `false` otherwise.
    fn ack(
        &mut self,
        stream: &StreamName,
        group: &GroupName,
        id: &MessageId,
    ) -> RedsumerResult<bool>;
}
